// Full state and actual SVG parity for the in-memory Undo control.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { chromium, webkit } = require('playwright');
const base = process.env.RPI_SITE_URL || 'http://127.0.0.1:8891';
const engine = process.env.RPI_BROWSER || 'chromium';
const evidence = process.env.RPI_EVIDENCE_DIR || `/tmp/randomize-undo-${engine}`;
const styles = ['ruler', 'binary', 'morse', 'ticker', 'waveform', 'wave-quantum', 'circles', 'numeric',
  'circles-gradient', 'gradient', 'grid', 'lines', 'point-connect', 'neural-network', 'triangle-grid', 'triangles'];
const action = (page, style, name) => page.locator(`[data-parameter-action="${name}"][data-parameter-style="${style}"]`);
const undo = (page, style) => page.locator(`[data-randomize-undo="${style}"]`);
const state = page => page.evaluate(() => barShareController.capture());
const svg = page => page.evaluate(() => captureLogoExportSnapshot().svgSource);
const png = async page => {
  await page.locator('#save-button').click();
  const download = page.waitForEvent('download');
  await page.locator('#save-png').click();
  const bytes = await fs.readFile(await (await download).path());
  await page.keyboard.press('Escape');
  return bytes;
};
const ready = page => page.waitForFunction(() => window.randomizeHistory && window.logoExportUI);
(async () => {
  await fs.mkdir(evidence, { recursive: true });
  const browser = await ({ chromium, webkit }[engine]).launch();
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1180, height: 757 }, reducedMotion: 'reduce' });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/generator/ruler/`); await ready(page);
    for (const style of styles) {
      await page.selectOption('#style-select', style, { force: true });
      const before = await state(page), artwork = await svg(page);
      await action(page, style, 'randomize').click();
      assert.equal(await undo(page, style).isEnabled(), true, `${style}: Undo enabled`);
      await undo(page, style).click();
      const after = await state(page);
      assert.deepEqual(after.controls, before.controls, `${style}: all controls including inactive values`);
      assert.equal(after.runtime.seed, before.runtime.seed, `${style}: exact seed`);
      assert.equal(await svg(page), artwork, `${style}: actual SVG restored exactly`);
      assert.equal(await undo(page, style).isEnabled(), false, `${style}: only one undo`);
      assert.equal(await action(page, style, 'randomize').evaluate(el => el === document.activeElement), true, `${style}: focus returns to Randomize`);
      console.log(`PASS ${style}: exact configuration, seed and SVG`);
    }
    await page.selectOption('#style-select', 'circles', { force: true });
    await action(page, 'circles', 'randomize').click();
    const first = await state(page), firstSvg = await svg(page), firstPng = await png(page);
    await action(page, 'circles', 'randomize').click();
    await undo(page, 'circles').focus(); await page.keyboard.press('Enter');
    assert.deepEqual((await state(page)).controls, first.controls);
    assert.equal((await state(page)).runtime.seed, first.runtime.seed);
    assert.equal(await svg(page), firstSvg);
    assert.deepEqual(await png(page), firstPng, 'Circles actual PNG bytes restored exactly');
    await page.goto(await page.evaluate(() => barShareController.buildLink())); await ready(page);
    const shared = await state(page);
    await action(page, 'circles', 'randomize').click(); await undo(page, 'circles').click();
    assert.deepEqual((await state(page)).controls, shared.controls, 'historical snapshot controls restored');
    assert.equal((await state(page)).runtime.seed, shared.runtime.seed, 'historical snapshot seed restored');
    await action(page, 'circles', 'randomize').click();
    await page.evaluate(() => window.dispatchEvent(new PopStateEvent('popstate')));
    assert.equal(await undo(page, 'circles').isEnabled(), false, 'history navigation expires Undo');
    await page.selectOption('#style-select', 'ruler', { force: true });
    await action(page, 'ruler', 'randomize').click();
    await page.locator('#ruler-repeats-display').click();
    await page.locator('.slider_value-input').fill('18'); await page.keyboard.press('Escape');
    assert.equal(await undo(page, 'ruler').isEnabled(), true, 'canceled numeric editor keeps Undo');
    await page.locator('#ruler-repeats-display').click();
    await page.locator('.slider_value-input').fill('17'); await page.keyboard.press('Enter');
    assert.equal(await undo(page, 'ruler').isEnabled(), false, 'committed numeric editor expires Undo');
    await action(page, 'ruler', 'randomize').click();
    await page.locator('#ruler-repeats-slider').focus();
    await page.keyboard.press(await page.inputValue('#ruler-repeats-slider') === '20' ? 'ArrowLeft' : 'ArrowRight');
    assert.equal(await undo(page, 'ruler').isEnabled(), false, 'native keyboard change expires Undo');
    await action(page, 'ruler', 'randomize').click();
    await action(page, 'ruler', 'reset').click();
    assert.equal(await undo(page, 'ruler').isEnabled(), false, 'Reset expires Undo');
    await action(page, 'ruler', 'randomize').click();
    await page.selectOption('#color-mode-select', 'red', { force: true });
    assert.equal(await undo(page, 'ruler').isEnabled(), false, 'theme edit expires Undo');
    await action(page, 'ruler', 'randomize').click();
    await page.selectOption('#style-select', 'solid', { force: true });
    assert.equal(await undo(page, 'ruler').isEnabled(), false, 'style edit expires Undo');
    assert.equal(await page.locator('[data-randomize-undo="solid"]').count(), 0, 'fixed artwork has no Undo');
    await page.selectOption('#style-select', 'circles', { force: true });
    await action(page, 'circles', 'randomize').click();
    await page.screenshot({ path: `${evidence}/desktop.png` });
    await page.setViewportSize({ width: 375, height: 812 });
    await page.locator('#mobile-menu-toggle').click();
    await page.screenshot({ path: `${evidence}/phone.png` });
    const bounds = await undo(page, 'circles').boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 375, 'phone Undo stays inside viewport');
    await undo(page, 'circles').click();
    assert.equal(await undo(page, 'circles').isEnabled(), false, 'touch-sized layout Undo works');
    await page.reload(); await ready(page);
    assert.equal(await undo(page, 'circles').isEnabled(), false, 'Undo is not persisted');
    const live = await browser.newPage({ viewport: { width: 1180, height: 757 }, reducedMotion: 'no-preference' });
    live.on('pageerror', error => errors.push(error.message));
    await live.goto(`${base}/generator/wave-quantum/`); await ready(live);
    assert.equal(await live.locator('#quantum-motion-toggle').isChecked(), true);
    await action(live, 'wave-quantum', 'randomize').click();
    await undo(live, 'wave-quantum').click();
    assert.equal(await live.locator('#quantum-motion-toggle').isChecked(), true, 'local Undo preserves running Quantum');
    await live.locator('label[for="quantum-motion-toggle"]').click();
    const frozen = await svg(live);
    await action(live, 'wave-quantum', 'randomize').click(); await undo(live, 'wave-quantum').click();
    assert.equal(await live.locator('#quantum-motion-toggle').isChecked(), false, 'local Undo preserves paused Quantum');
    assert.equal(await svg(live), frozen, 'paused Quantum phase restores exactly');
    assert.deepEqual(errors, []);
    await fs.writeFile(`${evidence}/results.json`, JSON.stringify({ engine, styles, errors, exactSvg: true, exactPng: true, historicalSnapshots: true, repeatedUndo: true, invalidation: true, keyboard: true, mobile: true, quantumTransport: true }, null, 2));
    console.log(`${engine}: all Undo checks passed`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
